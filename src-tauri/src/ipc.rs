//! Thin wrapper around `tauri-specta`, the only module that names it, so it can be replaced
//! without touching the rest of the app (docs/third-party-risk.md, CR-002 D7).
//!
//! Every IPC command is registered here once; the TypeScript bindings in `ui/src/bindings.ts`
//! are generated from the same list (no hand-written command types, CLAUDE.md stack).

use std::path::Path;
use std::sync::LazyLock;

use specta_typescript::Typescript;
use tauri::ipc::Invoke;
use tauri::Wry;
use tauri_specta::{collect_commands, collect_events, Builder};

/// Committed bindings file, relative to this crate's manifest directory.
pub const BINDINGS_PATH: &str = "../ui/src/bindings.ts";

const BINDINGS_HEADER: &str = "// Generated by src-tauri/src/ipc.rs (tauri-specta). Do not edit.\n\
// Regenerate: CAELUM_UPDATE_BINDINGS=1 cargo test -p caelum-desktop ipc::\n";

/// Error from generating the TypeScript bindings.
#[derive(Debug)]
pub struct BindingsError(String);

impl std::fmt::Display for BindingsError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "failed to export IPC bindings: {}", self.0)
    }
}

impl std::error::Error for BindingsError {}

/// The single command registry. The invoke handler borrows it, and Tauri needs that borrow to be
/// `'static`, so it lives for the whole process.
static BUILDER: LazyLock<Builder<Wry>> = LazyLock::new(|| {
    Builder::<Wry>::new()
        .commands(collect_commands![
            crate::commands::app_info,
            crate::commands::auth_login,
            crate::commands::auth_logout,
            crate::commands::auth_me,
            crate::commands::auth_reauth,
            crate::commands::break_glass_open,
            crate::commands::audit_list,
            crate::commands::audit_verify,
            crate::commands::ruleset_status,
            crate::commands::alarm_acknowledge,
            crate::commands::alarm_silence,
            crate::commands::alarm_escalate,
            crate::commands::setup_status,
            crate::commands::setup_create_administrator,
        ])
        .events(collect_events![crate::events::AlarmBusEvent])
});

/// Registers the typed events with the running app (call once in `setup`).
pub fn mount_events(app: &tauri::App) {
    BUILDER.mount_events(app);
}

/// The invoke handler for every registered command.
pub fn invoke_handler() -> impl Fn(Invoke<Wry>) -> bool + Send + Sync + 'static {
    BUILDER.invoke_handler()
}

/// Writes the TypeScript bindings for every registered command to `path`.
pub fn export_bindings(path: &Path) -> Result<(), BindingsError> {
    BUILDER
        .export(Typescript::default().header(BINDINGS_HEADER), path)
        .map_err(|e| BindingsError(e.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn normalised(text: &str) -> String {
        text.replace("\r\n", "\n")
    }

    /// Drift check (CLAUDE.md stack: no hand-written command types): the committed bindings must
    /// equal freshly generated ones. Set `CAELUM_UPDATE_BINDINGS=1` to rewrite the committed file.
    #[test]
    fn committed_bindings_match_generated_bindings() {
        let committed = Path::new(env!("CARGO_MANIFEST_DIR")).join(BINDINGS_PATH);
        if std::env::var_os("CAELUM_UPDATE_BINDINGS").is_some() {
            export_bindings(&committed).expect("bindings must export");
        }
        let generated_path =
            std::env::temp_dir().join(format!("caelum-bindings-{}.ts", std::process::id()));
        export_bindings(&generated_path).expect("bindings must export");
        let generated = std::fs::read_to_string(&generated_path).expect("generated bindings");
        let _ = std::fs::remove_file(&generated_path);
        let current = std::fs::read_to_string(&committed).unwrap_or_else(|_| {
            panic!(
                "{} is missing; run with CAELUM_UPDATE_BINDINGS=1",
                committed.display()
            )
        });
        assert_eq!(
            normalised(&current),
            normalised(&generated),
            "ui/src/bindings.ts is out of date; run with CAELUM_UPDATE_BINDINGS=1"
        );
    }

    /// The bindings expose `appInfo` and its result type to the UI.
    #[test]
    fn bindings_contain_app_info_command_and_type() {
        let path =
            std::env::temp_dir().join(format!("caelum-bindings-check-{}.ts", std::process::id()));
        export_bindings(&path).expect("bindings must export");
        let text = std::fs::read_to_string(&path).expect("generated bindings");
        let _ = std::fs::remove_file(&path);
        assert!(text.contains("appInfo"), "command missing:\n{text}");
        assert!(text.contains("AppInfo"), "type missing:\n{text}");
        assert!(text.contains("productName"), "field missing:\n{text}");
    }
}
